package com.enlil.universe.civilization.polity;

/** How a head of state comes to power. */
public enum Succession {
    /** By birth, within a dynasty. */
    HEREDITARY,
    /** By a vote: of the people, of a parliament, of fellow rulers or of a college (the cardinals electing a pope). */
    ELECTED,
    /** Handed power by another body, as the French parliament granted Pétain full powers in 1940. */
    APPOINTED
}
