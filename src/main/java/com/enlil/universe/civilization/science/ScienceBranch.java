package com.enlil.universe.civilization.science;

/** The great branches of science, by what they study and how. */
public enum ScienceBranch {
    /** Abstract structures, studied by proof rather than experiment. */
    FORMAL,
    /** Nature, studied by observation and experiment. */
    NATURAL,
    /** People and societies. */
    SOCIAL,
    /** Knowledge put to practical use. */
    APPLIED
}
