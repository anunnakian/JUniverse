package com.enlil.universe.geoscience;

/**
 * How two tectonic plates meet.
 */
public enum BoundaryType {
    /** The plates move apart and new crust wells up between them: mid-ocean ridges, rifts. */
    DIVERGENT,
    /** The plates collide: one sinks under the other, or both crumple into mountains. */
    CONVERGENT,
    /** The plates slide past each other: faults. */
    TRANSFORM
}
