package com.enlil.universe.geoscience;

/**
 * The processes of the rock cycle, each making one type of rock.
 */
public enum RockCycleProcess {
    /** Erosion, then deposition and compaction into sedimentary rock. */
    WEATHERING,
    /** Heat and pressure recrystallizing rock without melting it. */
    METAMORPHISM,
    /** Melting into magma, which cools into igneous rock. */
    MELTING
}
