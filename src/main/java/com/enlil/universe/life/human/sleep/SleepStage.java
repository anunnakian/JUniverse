package com.enlil.universe.life.human.sleep;

/** The stages of sleep, as scored by the American Academy of Sleep Medicine since 2007. */
public enum SleepStage {
    /** Non-REM 1: dozing off, a few minutes at each cycle's start. */
    N1,
    /** Non-REM 2: light sleep, about half the night, with its sleep spindles. */
    N2,
    /** Non-REM 3: deep, slow-wave sleep, mostly in the first cycles of the night. */
    N3,
    /** Rapid eye movement: the brain as active as awake, the body paralysed, and most dreams. */
    REM
}
