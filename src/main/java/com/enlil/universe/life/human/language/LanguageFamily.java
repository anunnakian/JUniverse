package com.enlil.universe.life.human.language;

/** The great language families, by number of native speakers. */
public enum LanguageFamily {
    /** From Hindi to English, French and Latin: nearly half of humanity. */
    INDO_EUROPEAN,
    /** Mandarin and the other Chinese languages, Tibetan, Burmese. */
    SINO_TIBETAN,
    /** Yoruba, Swahili, Zulu... the largest family by number of languages. */
    NIGER_CONGO,
    /** Arabic, Hebrew, Amharic, Berber. */
    AFRO_ASIATIC,
    /** Indonesian, Malay, Tagalog, Malagasy, Hawaiian. */
    AUSTRONESIAN,
    /** Tamil, Telugu, Kannada, Malayalam. */
    DRAVIDIAN,
    /** Turkish, Uzbek, Kazakh. */
    TURKIC,
    /** Japanese and the Ryukyuan languages. */
    JAPONIC,
    /** Korean. */
    KOREANIC,
    /** A language with no known relative, like Basque. */
    ISOLATE
}
