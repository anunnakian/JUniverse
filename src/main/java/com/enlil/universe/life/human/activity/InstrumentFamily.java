package com.enlil.universe.life.human.activity;

/** The Hornbostel–Sachs classification of musical instruments (1914), by what vibrates to make the sound. */
public enum InstrumentFamily {
    /** The body of the instrument itself vibrates: xylophone, cymbals, bells. */
    IDIOPHONE,
    /** A stretched membrane: drums. */
    MEMBRANOPHONE,
    /** Stretched strings: guitar, violin, and the piano, whose strings are struck. */
    CHORDOPHONE,
    /** A column of air: flute, trumpet, saxophone. */
    AEROPHONE,
    /** Electronic oscillators, added in 1940: synthesizer, theremin. */
    ELECTROPHONE
}
